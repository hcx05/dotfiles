#!/usr/bin/env bash
# Regenerates every color file derived from ~/.config/rice/theme.conf.
# Run this after editing theme.conf, then reload i3 (Mod+Shift+c) and
# restart polybar/picom/dunst (or just log out and back in).
set -euo pipefail

THEME_DIR="$HOME/.config/rice"
# shellcheck source=theme.conf
source "$THEME_DIR/theme.conf"

strip_hash() { echo "${1#\#}"; }

# Fixed neutral black for the kitty terminal canvas specifically -- NOT
# derived from $BACKGROUND. $BACKGROUND is deliberately a near-black tinted
# with the theme hue (green-black / purple-black) and that's fine as a
# solid, opaque surface (i3 borders, polybar, tab bar), but once kitty
# blends it with the desktop via background_opacity, that tint becomes
# visible as a colored haze over the transparent terminal background. Using
# plain black here keeps the terminal canvas neutral across every theme
# while the accent/foreground colors still carry the theme color.
TERM_BACKGROUND="#000000"
# Terminal text color: presets may set TERMINAL_FOREGROUND to give kitty a
# different text color than the bar/menus (mono: pure white); otherwise it
# just follows FOREGROUND.
TERM_FOREGROUND="${TERMINAL_FOREGROUND:-$FOREGROUND}"

# alpha byte (00-ff) from a 0.0-1.0 float, for AARRGGBB hex strings
alpha_byte() { awk -v a="$1" 'BEGIN{printf "%02x", (a*255)+0.5}'; }

BG_NOHASH=$(strip_hash "$BACKGROUND")
BGALT_NOHASH=$(strip_hash "$BACKGROUND_ALT")
FG_NOHASH=$(strip_hash "$FOREGROUND")
FGALT_NOHASH=$(strip_hash "$FOREGROUND_ALT")
ACCENT_NOHASH=$(strip_hash "$ACCENT")
ACCENTALT_NOHASH=$(strip_hash "$ACCENT_ALT")
BORDERACT_NOHASH=$(strip_hash "$BORDER_ACTIVE")
BORDERINACT_NOHASH=$(strip_hash "$BORDER_INACTIVE")
URGENT_NOHASH=$(strip_hash "$URGENT")

BAR_ALPHA=$(alpha_byte "$BAR_TRANSPARENCY")
MENU_ALPHA=$(alpha_byte "$MENU_TRANSPARENCY")

DUNST_TRANSPARENCY_PCT=$(awk -v t="$MENU_TRANSPARENCY" 'BEGIN{printf "%d", (1-t)*100}')

# ---------------------------------------------------------------- i3 -----
# i3's `include` directive does NOT propagate `set` variables back to the
# parent file (variable substitution is a preprocessing pass done before
# includes are resolved), so the color `set` lines are injected directly
# into i3/config between markers instead of a separate included file.
I3_CONFIG="$HOME/.config/i3/config"
I3_COLOR_BLOCK=$(cat <<EOF
# BEGIN GENERATED COLORS (regenerated by ~/.config/rice/apply-theme.sh)
set \$bg          $BACKGROUND
set \$bg_alt      $BACKGROUND_ALT
set \$fg          $FOREGROUND
set \$fg_alt      $FOREGROUND_ALT
set \$accent      $ACCENT
set \$accent_alt  $ACCENT_ALT
set \$border_active   $BORDER_ACTIVE
set \$border_inactive $BORDER_INACTIVE
set \$urgent      $URGENT
# END GENERATED COLORS
EOF
)
# Replaces everything between "# BEGIN <name>" and "# END <name>" in
# i3/config with $2 (which carries its own BEGIN/END marker lines).
replace_i3_block() {
  awk -v name="$1" -v block="$2" '
    $0 ~ "# BEGIN " name { print block; skip=1; next }
    $0 ~ "# END " name { skip=0; next }
    !skip { print }
  ' "$I3_CONFIG" > "$I3_CONFIG.tmp" && mv "$I3_CONFIG.tmp" "$I3_CONFIG"
}
replace_i3_block "GENERATED COLORS" "$I3_COLOR_BLOCK"

# ------------------------------------------------------------- layout ----
# LAYOUT="classic" (purple/green -- the default when a preset doesn't set
#   it): full-width bar/mainbar docked at the top; i3 reserves its strip
#   on its own (polybar is a regular dock client there).
# LAYOUT="dock" (mono): floating outlined bar/monobar at the top plus the
#   Ubuntu-style app dock (~/.config/rice/dock/dock.py) on the right edge.
#   Both are override-redirect, so i3 reserves NOTHING for them by itself --
#   the numbers below are what keeps windows off them:
#     layout.json -> maximize-toggle.py / default-size.py /
#                    fix-maximized-on-output-change.py (floating windows),
#                    and the dock's own geometry/colors
#     i3 gaps     -> tiled windows (workspace 4)
#
# BAR STYLE OVERRIDE (bar-selector.sh / $mod+Shift+t): the taskbar style is
# normally whatever the active color theme's own LAYOUT says (mono = dock,
# purple/green = classic), but it's a genuinely separate axis from color --
# ~/.config/rice/.barstyle, when present and non-empty, wins over the
# theme's own LAYOUT so "taskbar選擇" can mix any bar style with any color
# theme. Written only by bar-selector.sh; absent/empty means "follow the
# theme" (original behavior, unchanged).
BARSTYLE_OVERRIDE_FILE="$THEME_DIR/.barstyle"
if [ -s "$BARSTYLE_OVERRIDE_FILE" ]; then
    LAYOUT="$(tr -d ' \t\n\r' < "$BARSTYLE_OVERRIDE_FILE")"
fi
LAYOUT="${LAYOUT:-classic}"
EDGE_GAP="${EDGE_GAP:-8}"
TOPBAR_WIDTH="${TOPBAR_WIDTH:-76%}"
TOPBAR_OFFSET_X="${TOPBAR_OFFSET_X:-12%}"
TOPBAR_HEIGHT="${TOPBAR_HEIGHT:-26}"
TOPBAR_BORDER="${TOPBAR_BORDER:-2}"
DOCK_ICON_SIZE="${DOCK_ICON_SIZE:-18}"
DOCK_LENGTH="${DOCK_LENGTH:-0.85}"   # max fraction of screen height before dock icons shrink
# icon + 2*(dock outline 1 + button margin 1 + icon margin 2) -- keep in
# sync with the CSS in dock.py (18 + 8 = 26px, matching mainbar height)
DOCK_WIDTH=$((DOCK_ICON_SIZE + 8))
WINDOW_MARGIN=4   # gap kept around maximized/tiled windows at screen edges
I3_INNER_GAP=$(awk '$1=="gaps" && $2=="inner" {print $3; exit}' "$I3_CONFIG")
I3_INNER_GAP="${I3_INNER_GAP:-0}"
EDGE_OUTER_GAP=$((WINDOW_MARGIN - I3_INNER_GAP))

if [ "$LAYOUT" = "dock" ]; then
  RESERVED_TOP=$((EDGE_GAP + TOPBAR_HEIGHT + 2 * TOPBAR_BORDER))
  RESERVED_RIGHT=$((EDGE_GAP + DOCK_WIDTH))
  # i3 puts inner + outer gap at a workspace edge, hence "- inner" here on all
  # 4 sides so tiled windows align to the exact same margin as floating ones.
  I3_LAYOUT_LINES="smart_gaps off
gaps outer $EDGE_OUTER_GAP
gaps top $((RESERVED_TOP + WINDOW_MARGIN - I3_INNER_GAP))
gaps right $((RESERVED_RIGHT + WINDOW_MARGIN - I3_INNER_GAP))"
  DUNST_OFFSET="($((RESERVED_RIGHT + 12)), $((RESERVED_TOP + 10)))"
else
  RESERVED_TOP=$(awk '/^\[bar\/mainbar\]/{f=1; next} /^\[/{f=0} f && $1=="height" {print $3; exit}' \
    "$HOME/.config/polybar/config.ini")
  RESERVED_TOP="${RESERVED_TOP:-26}"
  RESERVED_RIGHT=0
  I3_LAYOUT_LINES="smart_gaps off
gaps outer $EDGE_OUTER_GAP"
  DUNST_OFFSET="(12, 40)"
fi

replace_i3_block "GENERATED LAYOUT" "# BEGIN GENERATED LAYOUT (regenerated by ~/.config/rice/apply-theme.sh)
$I3_LAYOUT_LINES
# END GENERATED LAYOUT"

cat > "$THEME_DIR/layout.json" <<EOF
{
  "_comment": "GENERATED by ~/.config/rice/apply-theme.sh -- do not edit by hand. Source of truth: ~/.config/rice/theme.conf",
  "layout": "$LAYOUT",
  "reserved": {"top": $RESERVED_TOP, "right": $RESERVED_RIGHT, "bottom": 0, "left": 0},
  "window_margin": $WINDOW_MARGIN,
  "edge_gap": $EDGE_GAP,
  "dock": {"width": $DOCK_WIDTH, "icon_size": $DOCK_ICON_SIZE, "length": $DOCK_LENGTH},
  "colors": {
    "background": "$BACKGROUND", "background_alt": "$BACKGROUND_ALT",
    "foreground": "$FOREGROUND", "foreground_alt": "$FOREGROUND_ALT",
    "accent": "$ACCENT", "accent_alt": "$ACCENT_ALT",
    "border_active": "$BORDER_ACTIVE",
    "border_inactive": "$BORDER_INACTIVE", "urgent": "$URGENT"
  },
  "bar_transparency": $BAR_TRANSPARENCY
}
EOF

# ------------------------------------------------------------ polybar ----
cat > "$HOME/.config/polybar/colors.ini" <<EOF
; GENERATED by ~/.config/rice/apply-theme.sh -- do not edit by hand.
; Source of truth: ~/.config/rice/theme.conf
[colors]
background = #${BAR_ALPHA}${BG_NOHASH}
background-alt = #${BGALT_NOHASH}
foreground = ${FOREGROUND}
foreground-alt = ${FOREGROUND_ALT}
accent = ${ACCENT}
accent-alt = ${ACCENT_ALT}
border-active = ${BORDER_ACTIVE}
border-inactive = ${BORDER_INACTIVE}
urgent = ${URGENT}
EOF

cat > "$HOME/.config/polybar/layout.ini" <<EOF
; GENERATED by ~/.config/rice/apply-theme.sh -- do not edit by hand.
; Source of truth: ~/.config/rice/theme.conf (EDGE_GAP / TOPBAR_*)
; Geometry of bar/monobar (LAYOUT="dock"); launch.sh picks which bar to run.
[layout]
monobar-width = ${TOPBAR_WIDTH}
monobar-offset-x = ${TOPBAR_OFFSET_X}
monobar-offset-y = ${EDGE_GAP}
monobar-height = ${TOPBAR_HEIGHT}
monobar-border = ${TOPBAR_BORDER}
EOF

# -------------------------------------------------------------- rofi -----
cat > "$HOME/.config/rofi/colors.rasi" <<EOF
/* GENERATED by ~/.config/rice/apply-theme.sh -- do not edit by hand. */
/* Source of truth: ~/.config/rice/theme.conf */
* {
    bg:        rgba($((16#${BG_NOHASH:0:2})), $((16#${BG_NOHASH:2:2})), $((16#${BG_NOHASH:4:2})), 100%);
    bg-trans:  rgba($((16#${BG_NOHASH:0:2})), $((16#${BG_NOHASH:2:2})), $((16#${BG_NOHASH:4:2})), ${MENU_TRANSPARENCY});
    bg-alt:    ${BACKGROUND_ALT};
    fg:        ${FOREGROUND};
    fg-alt:    ${FOREGROUND_ALT};
    accent:    ${ACCENT};
    accent-alt: ${ACCENT_ALT};
    border-active: ${BORDER_ACTIVE};
    urgent:    ${URGENT};
}
EOF

# -------------------------------------------------------------- kitty ----
cat > "$HOME/.config/kitty/colors.conf" <<EOF
# GENERATED by ~/.config/rice/apply-theme.sh -- do not edit by hand.
# Source of truth: ~/.config/rice/theme.conf
background            ${TERM_BACKGROUND}
foreground             ${TERM_FOREGROUND}
background_opacity    ${TERMINAL_TRANSPARENCY}
cursor                ${ACCENT}
cursor_text_color     ${TERM_BACKGROUND}
selection_background  ${ACCENT}
selection_foreground  ${TERM_BACKGROUND}
url_color             ${ACCENT}
active_border_color   ${BORDER_ACTIVE}
inactive_border_color ${BORDER_INACTIVE}
bell_border_color     ${URGENT}
tab_bar_background     ${TERM_BACKGROUND}
active_tab_background  ${BACKGROUND_ALT}
active_tab_foreground  ${ACCENT}
inactive_tab_background ${TERM_BACKGROUND}
inactive_tab_foreground ${FOREGROUND_ALT}

# 16-color palette
color0  ${BACKGROUND_ALT}
color8  ${FOREGROUND_ALT}
color1  ${URGENT}
color9  ${URGENT}
color2  ${ACCENT_ALT}
color10 ${ACCENT_ALT}
color3  ${TERMINAL_COLOR3:-#E3C878}
color11 ${TERMINAL_COLOR3:-#E3C878}
color4  ${ACCENT}
color12 ${ACCENT}
color5  ${TERMINAL_COLOR5:-#B48EAD}
color13 ${TERMINAL_COLOR5:-#B48EAD}
color6  ${ACCENT}
color14 ${ACCENT}
color7  ${FOREGROUND}
color15 #FFFFFF
EOF

# ------------------------------------------------------- tmux style ----
# Presets pick a tmux status look with TERMINAL_STYLE ("classic" = the
# purple/green powerline segments, "mono" = plain white text). tmux's status
# script reads this one word itself every refresh (see switch-theme.sh).
TERMINAL_STYLE="${TERMINAL_STYLE:-classic}"
echo "$TERMINAL_STYLE" > "$THEME_DIR/terminal-style"

# tmux status bar surface: classic keeps its black strip, mono drops every
# background so only the white status text is left. Sourced by ~/.tmux.conf.
if [ "$TERMINAL_STYLE" = "mono" ]; then
    TMUX_STATUS_STYLE="bg=default,fg=white"
else
    TMUX_STATUS_STYLE="bg=black,fg=white"
fi
cat > "$THEME_DIR/tmux-theme.conf" <<EOF
# GENERATED by ~/.config/rice/apply-theme.sh -- do not edit by hand.
set -g status-style ${TMUX_STATUS_STYLE}
EOF

# -------------------------------------------------------------- dunst ----
sed \
  -e "s/@@BACKGROUND@@/${BG_NOHASH}/g" \
  -e "s/@@FOREGROUND@@/${FG_NOHASH}/g" \
  -e "s/@@ACCENT@@/${ACCENT_NOHASH}/g" \
  -e "s/@@ACCENT_ALT@@/${ACCENTALT_NOHASH}/g" \
  -e "s/@@BORDER_INACTIVE@@/${BORDERINACT_NOHASH}/g" \
  -e "s/@@URGENT@@/${URGENT_NOHASH}/g" \
  -e "s/@@TRANSPARENCY_PCT@@/${DUNST_TRANSPARENCY_PCT}/g" \
  -e "s/@@OFFSET@@/${DUNST_OFFSET}/g" \
  "$THEME_DIR/dunstrc.template" > "$HOME/.config/dunst/dunstrc"

# -------------------------------------------------------------- picom ----
TRANSPARENCY_PCT=$(awk -v t="$MENU_TRANSPARENCY" 'BEGIN{printf "%d", (t*100)+0.5}')
BAR_TRANSPARENCY_PCT=$(awk -v t="$BAR_TRANSPARENCY" 'BEGIN{printf "%d", (t*100)+0.5}')
sed \
  -e "s/@@TRANSPARENCY_PCT@@/${TRANSPARENCY_PCT}/g" \
  -e "s/@@BAR_TRANSPARENCY_PCT@@/${BAR_TRANSPARENCY_PCT}/g" \
  "$THEME_DIR/picom.conf.template" > "$HOME/.config/picom/picom.conf"

# ---------------------------------------------- firefox & startup-page ---
FF_COLORS_CSS=$(cat <<EOF
/** Style and colors generated by ~/.config/rice/apply-theme.sh **/

:root {
    --z0mbi3-bg: ${BACKGROUND};
    --z0mbi3-fg: ${FOREGROUND};
    --z0mbi3-accent-color: ${ACCENT};
    --z0mbi3-accent-color-inactive: ${BACKGROUND_ALT};
    --z0mbi3-black: ${BACKGROUND};
    --z0mbi3-red: ${URGENT};
    --z0mbi3-green: ${ACCENT_ALT};
    --z0mbi3-yellow: ${TERMINAL_COLOR3:-#E3C878};
    --z0mbi3-blue: ${ACCENT};
    --z0mbi3-magenta: ${ACCENT};
    --z0mbi3-cyan: ${ACCENT_ALT};
    --z0mbi3-white: ${FOREGROUND};
}
EOF
)
if [ -d "$THEME_DIR/firefox/chrome" ]; then
  printf '%s\n' "$FF_COLORS_CSS" > "$THEME_DIR/firefox/chrome/Colors.css"
fi
for ff_base in "$HOME/.mozilla/firefox" "$HOME/.config/mozilla/firefox"; do
  [ -d "$ff_base" ] || continue
  for ff_prof in "$ff_base"/*.default*; do
    [ -d "$ff_prof/chrome" ] || continue
    printf '%s\n' "$FF_COLORS_CSS" > "$ff_prof/chrome/Colors.css"
  done
done

for sp_dir in "$HOME/.local/share/startup-page" "$THEME_DIR/startup-page"; do
  [ -d "$sp_dir" ] || continue
  cat > "$sp_dir/colors.css" <<EOF
/** Style and colors generated by ~/.config/rice/apply-theme.sh **/

:root {
  /* Font Size */
  --fg-primary: 12vh; /* Time and Greetings */
  --fg-secondary: 3vh; /* Greetings and Weather widget */
  --fg-date: 8vh; /* Date */
  --fg-list: 2vh; /* Links List */
  --icon: 3vh; /* Icon Size */

  /* Fonts Color */
  --fg: ${FOREGROUND}; /* Foreground color */
  --sfg: ${BACKGROUND}; /* Secondary Foreground color */

  /* Light Colors  */
  --accent: ${ACCENT}; /* Hover color */
  --background: ${BACKGROUND}; /* Background color */
  --cards: ${BACKGROUND_ALT}; /* Cards color */

  /* Image background  */
  --imgbg: url(assets/background.jpg); /* Image URL */
  --imgcol: linear-gradient(
    rgba(255, 255, 255, 0.7),
    rgba(255, 255, 255, 0.7)
  ); /* Filter color */
}

.darktheme {
  /* Dark Colors  */
  --accent: ${ACCENT}; /* Hover color */
  --background: ${BACKGROUND}; /* Background color */
  --cards: ${BACKGROUND_ALT}; /* Cards color */

  /* Fonts Color */
  --fg: ${FOREGROUND}; /* Foreground color */
  --sfg: ${BACKGROUND}; /* Secondary Foreground color */

  /* Image background  */
  --imgcol: linear-gradient(
    rgba(0, 0, 0, 0.85),
    rgba(0, 0, 0, 0.85)
  ); /* Filter color */
}
EOF
done

echo "Theme applied. Reload i3 (Mod+Shift+c) and restart polybar/picom/dunst to see changes."
