"""Where a "maximized" floating window goes on an output -- shared by
maximize-toggle.py, default-size.py and fix-maximized-on-output-change.py
(imported from the scripts' own directory, which python puts on sys.path).

The strips taken by the bar / dock come from ~/.config/rice/layout.json,
generated by ~/.config/rice/apply-theme.sh from the active theme.conf:
  classic layout (purple/green): top = bar/mainbar's height, nothing else
  dock layout (mono):            top = floating monobar, right = app dock
All of those numbers are already real pixels for the current screen:
apply-theme.sh writes them as "design size (sizes.conf) x display scale", and
re-writes them whenever ~/.config/rice/scale/autoscale sees the screen
change. Nothing here is a fixed pixel count -- layout.json is re-read on
every call, so the daemons pick a new scale up without a restart.

If layout.json is missing (apply-theme.sh not re-run since it was added),
falls back to bar/mainbar's height from polybar's generated layout.ini.
"""
import json
import os
import re

LAYOUT_FILE = os.path.expanduser("~/.config/rice/layout.json")
POLYBAR_LAYOUT = os.path.expanduser("~/.config/polybar/layout.ini")

# Size a freshly opened window is "restored" to (un-maximized), as a share of
# the usable area -- a ratio, so it is right on any screen (it used to be a
# fixed 1400x900, which is this share of the 1920x1080 it was picked on).
NORMAL_FRACTION = (0.73, 0.87)


def _layout():
    with open(LAYOUT_FILE) as f:
        return json.load(f)


def bar_height():
    try:
        with open(POLYBAR_LAYOUT) as f:
            for line in f:
                m = re.match(r"^mainbar-height\s*=\s*(\d+)", line.strip())
                if m:
                    return int(m.group(1))
    except OSError:
        pass
    return 0


def reserved():
    """(top, right, bottom, left) px taken by the bar/dock on every output."""
    try:
        r = _layout()["reserved"]
        return r["top"], r["right"], r["bottom"], r["left"]
    except Exception:
        return bar_height(), 0, 0, 0


def margin():
    """px kept free around a maximized window (sizes.conf WINDOW_MARGIN x scale)."""
    try:
        return int(_layout()["window_margin"])
    except Exception:
        return 0


def maximized_rect(out_rect):
    """(x, y, width, height) filling out_rect minus the bar/dock strips."""
    top, right, bottom, left = reserved()
    m = margin()
    return (
        out_rect.x + left + m,
        out_rect.y + top + m,
        out_rect.width - left - right - 2 * m,
        out_rect.height - top - bottom - 2 * m,
    )


def normal_rect(out_rect):
    """(x, y, width, height) of the "normal" (restored) window size: a fixed
    share of the usable area, centered in it."""
    ux, uy, uw, uh = maximized_rect(out_rect)
    w, h = round(uw * NORMAL_FRACTION[0]), round(uh * NORMAL_FRACTION[1])
    return ux + (uw - w) // 2, uy + (uh - h) // 2, w, h
