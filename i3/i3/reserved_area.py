"""Where a "maximized" floating window goes on an output -- shared by
maximize-toggle.py, default-size.py and fix-maximized-on-output-change.py
(imported from the scripts' own directory, which python puts on sys.path).

The strips taken by the bar / dock come from ~/.config/rice/layout.json,
generated by ~/.config/rice/apply-theme.sh from the active theme.conf:
  classic layout (purple/green): top = bar/mainbar's height, nothing else
  dock layout (mono):            top = floating monobar, right = app dock
If layout.json is missing (apply-theme.sh not re-run since it was added),
falls back to the old behavior: bar/mainbar's height from polybar's config.
"""
import json
import os
import re

LAYOUT_FILE = os.path.expanduser("~/.config/rice/layout.json")
POLYBAR_CONF = os.path.expanduser("~/.config/polybar/config.ini")
MARGIN = 4  # matches theme's gaps outer, purely aesthetic


def bar_height(section):
    in_section = False
    with open(POLYBAR_CONF) as f:
        for line in f:
            line = line.strip()
            if line == f"[{section}]":
                in_section = True
                continue
            if in_section and line.startswith("["):
                break
            if in_section:
                m = re.match(r"^height\s*=\s*(\d+)", line)
                if m:
                    return int(m.group(1))
    return 30


def reserved():
    """(top, right, bottom, left) px taken by the bar/dock on every output."""
    try:
        with open(LAYOUT_FILE) as f:
            r = json.load(f)["reserved"]
        return r["top"], r["right"], r["bottom"], r["left"]
    except Exception:
        return bar_height("bar/mainbar"), 0, 0, 0


def maximized_rect(out_rect):
    """(x, y, width, height) filling out_rect minus the bar/dock strips."""
    top, right, bottom, left = reserved()
    return (
        out_rect.x + left + MARGIN,
        out_rect.y + top + MARGIN,
        out_rect.width - left - right - 2 * MARGIN,
        out_rect.height - top - bottom - 2 * MARGIN,
    )
